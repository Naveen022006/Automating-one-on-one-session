/** The id of every real page. The web router has one `lazy` module per id (typed `Record<SpaRouteId, ...>`). */
export type SpaRouteId = (typeof SPA_ROUTES)[number]["id"];

/**
 * "Not found" belongs to a group too, so a deployment that has only some groups enabled never serves a Not found page
 * from a group it did not switch on. They are not pages: they have no lazy module, and status 404.
 */
