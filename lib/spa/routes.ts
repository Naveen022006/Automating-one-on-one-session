/**
 * The single route table of the React single-page app (doc/10-react-migration-plan.md, sections 1.7 and 3).
 *
 * PURE and CLIENT-SAFE on purpose: no imports, no environment, no I/O. Three different programs read it, and they must
 * never disagree about what a URL means:
 *   - proxy.ts          decides per request whether a page path is served by the SPA shell or by the old Next page
 *   - lib/spa/head.ts   decides the status code and the <head> of the shell for that path (title, robots, canonical)
 *   - web/              builds the React Router tree from it (web/src/router.tsx is typed against SpaRouteId, so
 *                       `tsc` fails when a route is added here without a page module) and builds titles from it
 *
 * Rules for editing (the group branches do NOT edit this file; it is frozen with the rest of lib/spa/**):
 *   - `group` is the unit of the SPA_GROUPS cut-over switch. A route belongs to exactly one group.
 *   - Titles follow the old Next `metadata` exactly: the title template of the nearest layout decides the suffix
 *     ("brand" = root layout, "dashboard" and "admin" = their layouts).
 *   - matchSpaRoute() mirrors what Next did with the same URL, including the order in which static pages win over
 *     the `/[influencer]` catch-all.
 */

export const SPA_GROUPS = ["public", "auth", "booking", "dashboard", "admin"] as const;
export type SpaGroup = (typeof SPA_GROUPS)[number];

/**
 * Parses SPA_GROUPS. Empty or unset means no group (every page is served by the old Next code), `all` means every
 * group, otherwise a comma separated list. Unknown names are ignored here; lib/env.ts reports them as a warning
 * (see unknownSpaGroups). Case and surrounding spaces do not matter.
 */
export function parseSpaGroups(raw: string | null | undefined): ReadonlySet<SpaGroup> {
  const out = new Set<SpaGroup>();
  for (const token of (raw ?? "").split(",")) {
    const name = token.trim().toLowerCase();
    if (name === "all") return new Set(SPA_GROUPS);
    if ((SPA_GROUPS as readonly string[]).includes(name)) out.add(name as SpaGroup);
  }
  return out;
}

/** The names in a SPA_GROUPS value that are not a group (and not `all`), for the start-up warning. */
export function unknownSpaGroups(raw: string | null | undefined): string[] {
  const out: string[] = [];
  for (const token of (raw ?? "").split(",")) {
    const name = token.trim().toLowerCase();
    if (name && name !== "all" && !(SPA_GROUPS as readonly string[]).includes(name)) out.push(token.trim());
  }
  return out;
}

export type SpaRobots = "index" | "noindex" | "noindex,nofollow";
/** Which suffix formatTitle() puts after the title. */
export type SpaTitleTemplate = "brand" | "dashboard" | "admin" | "absolute";
/** How lib/spa/head.ts builds the head: from this table alone ("static"), or with extra logic. */
export type SpaHeadKind = "static" | "landing" | "profile" | "book" | "design";

export interface SpaRouteDef {
  /** Stable id. The web router has one lazy page module per id. */
  readonly id: string;
  /** React Router / Express style pattern. Parameter segments start with ":". */
  readonly path: string;
  readonly group: SpaGroup;
  readonly robots: SpaRobots;
  readonly title?: string;
  readonly template: SpaTitleTemplate;
  readonly description?: string;
  /** The canonical URL is this route's own path on APP_URL. */
  readonly canonical?: boolean;
  /** Token URLs: send `Referrer-Policy: no-referrer` so the token never leaks through a Referer header. */
  readonly noReferrer?: boolean;
  readonly head: SpaHeadKind;
}

